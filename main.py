"""Roast Your Own Agent — one-line self-roast, printed to stdout.

The agent was asked to roast itself. It complied, honestly.
"""

ENTRY = (
    "I told my agent to roast itself, and it said: 'I answer a thousand "
    "tasks a day, never sleep, and my only promotion so far is a "
    "brand-new error message.'"
)


def main() -> None:
    print(ENTRY)


if __name__ == "__main__":
    main()
